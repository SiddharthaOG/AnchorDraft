"""Shared internal models for the Phase 4 review engine pipeline.

These models represent the internal data structures used by the review pipeline.
They are distinct from the API models and database models to maintain clear
separation between untrusted model output, validated findings, and database records.
"""
from typing import Optional, List, Literal, Dict, Any
from pydantic import BaseModel, Field, field_validator, model_validator
from uuid import UUID
from enum import Enum


class FindingSource(str, Enum):
    """Source of a finding."""
    DETERMINISTIC = "deterministic"
    LLM = "llm"


class ModelFindingCandidate(BaseModel):
    """Untrusted structured output returned by an LLM.

    This model represents raw output from an LLM provider before validation.
    It does NOT include offsets, database IDs, or trusted category/severity.
    """
    ref_key: str = Field(..., description="Reference key of the rule or fact")
    issue: Literal["violation", "contradicts_fact", "outdated_fact", "unsupported_claim"]
    quote: str = Field(..., min_length=1, description="Quote from the draft text")
    explanation: str = Field(..., min_length=1, description="Explanation of the issue")
    suggestion: Optional[str] = Field(default=None, description="Suggested replacement text")
    confidence: Optional[float] = Field(default=None, ge=0.0, le=1.0, description="Confidence score 0.0-1.0")

    model_config = {
        "extra": "forbid",  # Reject unexpected fields from LLM
    }


class DeterministicFindingCandidate(BaseModel):
    """Candidate finding generated by a deterministic rule.

    Deterministic candidates are generated by the engine's rule engine
    and have different validation rules than model candidates.
    """
    ref_key: str = Field(..., description="Reference key of the rule")
    quote: str = Field(..., min_length=1, description="Quote from the draft text")
    start_offset: int = Field(ge=0, description="Start offset in the text")
    end_offset: int = Field(gt=0, description="End offset in the text (exclusive)")
    explanation: str = Field(..., min_length=1, description="Explanation of the issue")
    suggestion: Optional[str] = Field(default=None, description="Suggested replacement text")
    rule_category: str = Field(..., description="Category of the rule")
    severity: str = Field(..., description="Severity level")
    needs_reviewer: bool = Field(default=False, description="Whether reviewer sign-off is needed")

    @field_validator("end_offset")
    @classmethod
    def validate_offsets(cls, v: int, info) -> int:
        """Validate that end_offset > start_offset."""
        if "start_offset" in info.data and v <= info.data["start_offset"]:
            raise ValueError("end_offset must be greater than start_offset")
        return v

    model_config = {
        "extra": "forbid",
        "str_strip_whitespace": True,
    }


class ValidatedFinding(BaseModel):
    """A finding that has passed the shared citation validator and is ready for persistence.

    This model matches the existing `findings` database contract.
    Does NOT include rule_id or fact_id - the database function resolves these from ref_key.
    """
    source: Literal["deterministic", "llm"]
    ref_key: str
    category: str
    severity: str
    quote: str
    start_offset: int = Field(ge=0)
    end_offset: int = Field(gt=0)
    explanation: str = Field(min_length=1)
    suggestion: Optional[str] = None
    confidence: Optional[float] = Field(default=None, ge=0.0, le=1.0)
    needs_human: bool = False
    needs_reviewer: bool = False

    @field_validator("end_offset")
    @classmethod
    def validate_offsets(cls, v: int, info) -> int:
        """Validate that end_offset > start_offset."""
        if "start_offset" in info.data and v <= info.data["start_offset"]:
            raise ValueError("end_offset must be greater than start_offset")
        return v

    @field_validator("confidence")
    @classmethod
    def validate_confidence(cls, v: Optional[float]) -> Optional[float]:
        if v is not None and not (0.0 <= v <= 1.0):
            raise ValueError("confidence must be between 0.0 and 1.0")
        return v

    model_config = {
        "extra": "forbid",
    }


class DropReason(str, Enum):
    """Reasons a candidate finding may be dropped during validation."""
    SCHEMA_INVALID = "schema_invalid"
    UNKNOWN_REF = "unknown_ref"
    REF_MISMATCH = "ref_mismatch"
    QUOTE_NOT_FOUND = "quote_not_found"
    DUPLICATE = "duplicate"
    TOO_MANY = "too_many"


class ValidatorOutcome(BaseModel):
    """Result of validating a single candidate finding."""
    candidate_ref: str  # ref_key of the candidate for identification
    source: Literal["deterministic", "llm"]
    kept: bool
    drop_reason: Optional[Literal["schema_invalid", "unknown_ref", "ref_mismatch", 
                                   "quote_not_found", "duplicate", "too_many"]] = None
    validated_finding: Optional["ValidatedFinding"] = None

    @model_validator(mode="after")
    def validate_consistency(self) -> "ValidatorOutcome":
        if self.kept:
            if self.drop_reason is not None:
                raise ValueError("drop_reason must be None when kept is True")
            if self.validated_finding is None:
                raise ValueError("validated_finding must be provided when kept is True")
        else:
            if self.validated_finding is not None:
                raise ValueError("validated_finding must be None when kept is False")
            if self.drop_reason is None:
                raise ValueError("drop_reason must be provided when kept is False")
            valid_reasons = {"schema_invalid", "unknown_ref", "ref_mismatch", 
                           "quote_not_found", "duplicate", "too_many"}
            if self.drop_reason not in {"schema_invalid", "unknown_ref", "ref_mismatch", 
                                         "quote_not_found", "duplicate", "too_many"}:
                raise ValueError(f"Invalid drop reason: {self.drop_reason}")
        return self

    model_config = {
        "extra": "forbid",
    }


class AggregateValidationResult(BaseModel):
    """Aggregate result of the validation process."""
    validated_findings: List["ValidatedFinding"] = Field(default_factory=list)
    raw_candidate_count: int = 0
    kept_count: int = 0
    dropped_counts: Dict[str, int] = Field(default_factory=dict)

    model_config = {
        "extra": "forbid",
    }

    def add_kept(self, finding: "ValidatedFinding") -> None:
        """Add a kept finding to the result."""
        self.validated_findings.append(finding)
        self.kept_count += 1
        self.raw_candidate_count += 1

    def add_dropped(self, reason: str) -> None:
        """Add a dropped candidate with the given reason."""
        valid_reasons = {"schema_invalid", "unknown_ref", "ref_mismatch", 
                         "quote_not_found", "duplicate", "too_many"}
        if reason not in valid_reasons:
            raise ValueError(f"Invalid drop reason: {reason}")
        self.dropped_counts[reason] = self.dropped_counts.get(reason, 0) + 1
        self.raw_candidate_count += 1


class ProviderRequest(BaseModel):
    """Request to the LLM provider."""
    system_instruction: str
    user_content: str
    output_schema: Dict[str, Any]
    randomness: float = Field(default=0.1, ge=0.0, le=1.0)
    output_limit: int = Field(default=4096, gt=0)
    timeout_seconds: int = Field(default=45, gt=0)

    model_config = {
        "extra": "forbid",
    }


class ProviderResult(BaseModel):
    """Result from the LLM provider."""
    raw_json: str
    input_tokens: int = Field(ge=0)
    output_tokens: int = Field(ge=0)
    model: str
    latency_ms: int = Field(ge=0)
    finish_reason: str

    model_config = {
        "extra": "forbid",
    }


class ProviderError(Exception):
    """Base exception for provider errors."""
    def __init__(self, message: str, retry_after: Optional[int] = None):
        super().__init__(message)
        self.retry_after = retry_after


class RateLimitedError(ProviderError):
    """Provider rate limited."""
    pass


class TimeoutError(ProviderError):
    """Provider timeout."""
    pass


class UnavailableError(ProviderError):
    """Provider unavailable."""
    pass


class BadOutputError(ProviderError):
    """Provider returned invalid output."""
    pass


class BlockedError(ProviderError):
    """Provider blocked the request (safety filter)."""
    pass


